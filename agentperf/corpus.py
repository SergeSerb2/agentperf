"""Deterministic synthetic source tree that every benchmark works on.

The corpus must be byte-identical on every machine and every Python version,
so all pseudo-random choices come from SHA-256 of a counter, not from the
`random` module. Files are written in binary mode with '\\n' line endings.
"""

from __future__ import annotations

import hashlib
import json
import os
from typing import List

from . import SUITE_VERSION
from .util import rmtree

CORPUS_FORMAT = 1  # bump when generation changes; it invalidates cached corpora
FILE_COUNT = 6000
NEEDLE = "NEEDLE_TOKEN_42"
NEEDLE_EVERY = 97
REGEX = r"def compute_(agent|cache|token)_[0-9]{3}\("

_TOP = ["src", "lib", "packages", "services", "tests", "tools", "docs", "web"]
_EXT = [".py", ".ts", ".js", ".go", ".rs", ".py", ".ts", ".md", ".json", ".py"]
_WORDS = (
    "agent cache token stream buffer parser render config index search graph "
    "commit branch worker queue socket client server request response handler "
    "schema record vector matrix tensor layout widget router session account "
    "billing invoice ledger payment refund order cart item stock price market "
    "event signal metric trace span logger health probe deploy build bundle "
    "module import export package version release patch delta merge rebase "
    "context prompt model tool result error retry timeout window frame state"
).split()
_LINES = [10, 18, 30, 45, 60, 80, 110, 150, 220, 320, 480, 900]
_TEMPLATES = [
    "def compute_{w0}_{n3}({w1}, {w2}):",
    "    {w0}_{w1} = {w2}.get_{w3}({n2})",
    "    if {w0} is None or {w1} > {n2}:",
    "        return {w2}_{w3}({w0}, retries={n1})",
    "    for {w0} in {w1}.{w2}_items():",
    "        {w0}.append({w1}[{n1}] + {w2})",
    "class {W0}{W1}Service:",
    "    \"\"\"Handle {w0} {w1} for the {w2} {w3} flow.\"\"\"",
    "# TODO({w0}): replace {w1} {w2} once {w3} lands",
    "import {w0}.{w1} as {w2}",
    "    raise ValueError(\"invalid {w0}: %s\" % {w1})",
    "    log.info(\"{w0} {w1} took %dms\", {n3})",
    "",
    "    return {{\"{w0}\": {w1}, \"{w2}\": {n2}}}",
    "    assert {w0}_{w1}({n2}) == {n3}",
    "    {w0} = await {w1}.{w2}({w3}=True)",
]


def _digest(*parts: str) -> bytes:
    return hashlib.sha256("\x1f".join(parts).encode("utf-8")).digest()


DIR_COUNT = 400


def _dirpath(k: int) -> List[str]:
    d = _digest("dir", str(k))
    parts = [_TOP[d[0] % len(_TOP)], "{}_{}".format(_WORDS[d[1] % len(_WORDS)], d[2] % 4)]
    depth = d[3] % 3
    if depth >= 1:
        parts.append(_WORDS[d[4] % len(_WORDS)])
    if depth >= 2:
        parts.append("{}{}".format(_WORDS[d[5] % len(_WORDS)], d[6] % 3))
    return parts


def _relpath(i: int) -> str:
    d = _digest("path", str(i))
    parts = _dirpath((d[0] << 8 | d[1]) % DIR_COUNT)
    name = "{}_{}_{:04d}{}".format(_WORDS[d[7] % len(_WORDS)], _WORDS[d[8] % len(_WORDS)], i,
                                    _EXT[d[9] % len(_EXT)])
    return "/".join(parts + [name])


def _content(i: int) -> bytes:
    d = _digest("size", str(i))
    nlines = _LINES[d[0] % len(_LINES)] + d[1] % 10
    out: List[str] = ["# generated by agentperf corpus v{} file {}".format(CORPUS_FORMAT, i)]
    nw = len(_WORDS)
    for ln in range(nlines):
        r = _digest("line", str(i), str(ln))
        w = [_WORDS[r[k] % nw] for k in range(1, 5)]
        line = _TEMPLATES[r[0] % len(_TEMPLATES)].format(
            w0=w[0], w1=w[1], w2=w[2], w3=w[3],
            W0=w[0].capitalize(), W1=w[1].capitalize(),
            n1=r[5] % 10, n2=r[6] * 7 % 1000, n3="{:03d}".format((r[7] << 8 | r[8]) % 1000),
        )
        out.append(line)
    if i % NEEDLE_EVERY == 0:
        out.insert(1 + (nlines // 2), "    marker = \"{}\"  # search target".format(NEEDLE))
    return ("\n".join(out) + "\n").encode("ascii")


class Corpus:
    """A generated tree at <root>/tree with a manifest at <root>/corpus.json."""

    def __init__(self, root: str):
        self.root = root
        self.tree = os.path.join(root, "tree")
        self.manifest_path = os.path.join(root, "corpus.json")
        self.files: List[str] = []
        self.total_bytes = 0
        self.fixture_hash = ""

    def ensure(self, log=print) -> "Corpus":
        if self._load():
            return self
        log("  generating corpus ({} files)...".format(FILE_COUNT))
        rmtree(self.root)
        os.makedirs(self.tree)
        h = hashlib.sha256()
        files = []
        total = 0
        made = set()
        for i in range(FILE_COUNT):
            rel = _relpath(i)
            data = _content(i)
            parent = os.path.dirname(rel)
            if parent not in made:
                os.makedirs(os.path.join(self.tree, *parent.split("/")), exist_ok=True)
                made.add(parent)
            with open(os.path.join(self.tree, *rel.split("/")), "wb") as fh:
                fh.write(data)
            h.update(rel.encode("utf-8") + b"\0" + data)
            files.append(rel)
            total += len(data)
        self.files = files
        self.total_bytes = total
        self.fixture_hash = h.hexdigest()[:16]
        with open(self.manifest_path, "w", encoding="utf-8") as fh:
            json.dump({"format": CORPUS_FORMAT, "suite": SUITE_VERSION, "files": files,
                       "total_bytes": total, "fixture_hash": self.fixture_hash}, fh)
        return self

    def _load(self) -> bool:
        try:
            with open(self.manifest_path, encoding="utf-8") as fh:
                data = json.load(fh)
        except (OSError, ValueError):
            return False
        if data.get("format") != CORPUS_FORMAT or len(data.get("files", [])) != FILE_COUNT:
            return False
        last = os.path.join(self.tree, *data["files"][-1].split("/"))
        if not os.path.exists(last):
            return False
        self.files = data["files"]
        self.total_bytes = data["total_bytes"]
        self.fixture_hash = data["fixture_hash"]
        return True

    def path(self, rel: str) -> str:
        return os.path.join(self.tree, *rel.split("/"))

    def subset(self, count: int) -> List[str]:
        """A fixed, evenly spread subset of relative paths."""
        step = max(1, len(self.files) // count)
        return self.files[::step][:count]
